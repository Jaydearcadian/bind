/**
 * Generates the typed client's sources from docs/openapi.json (docs/decisions/0036):
 *   sdk/src/generated/api.d.ts     the operation and schema types, from openapi-typescript
 *   sdk/src/generated/operations.ts the operation id -> method and path table, from the spec's own paths
 *
 * `npm run sdk:generate` writes both files. Both are committed. CI runs the generator and fails on any diff, and
 * tests/unit/sdk.test.ts regenerates them into a temporary directory and compares.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SPEC_PATH = path.join(ROOT, "docs/openapi.json");
export const GENERATED_DIR = path.join(ROOT, "sdk/src/generated");

const HTTP_METHODS = ["get", "post", "put", "delete", "patch"] as const;

export interface GeneratedFiles {
  "api.d.ts": string;
  "operations.ts": string;
}

interface OperationRow {
  operationId: string;
  method: string;
  path: string;
}

/** Every operation of the spec, sorted by id, so the table does not move when the spec is re-ordered. */
export function operationRows(spec: { paths?: Record<string, Record<string, unknown>> }): OperationRow[] {
  const rows: OperationRow[] = [];
  const seen = new Set<string>();
  for (const [template, item] of Object.entries(spec.paths ?? {})) {
    for (const method of HTTP_METHODS) {
      const op = item[method] as { operationId?: unknown } | undefined;
      if (!op) continue;
      if (typeof op.operationId !== "string" || op.operationId.length === 0) {
        throw new Error(`${method.toUpperCase()} ${template} has no operationId`);
      }
      if (seen.has(op.operationId)) throw new Error(`operationId ${op.operationId} is used twice`);
      seen.add(op.operationId);
      rows.push({ operationId: op.operationId, method: method.toUpperCase(), path: template });
    }
  }
  return rows.sort((a, b) => (a.operationId < b.operationId ? -1 : a.operationId > b.operationId ? 1 : 0));
}

function operationsSource(rows: OperationRow[]): string {
  const body = rows.map(
    (row) => `  ${JSON.stringify(row.operationId)}: { method: ${JSON.stringify(row.method)}, path: ${JSON.stringify(row.path)} },`
  );
  return [
    "// Generated by scripts/generate-sdk.ts from docs/openapi.json (docs/decisions/0036). Do not edit by hand: run npm run sdk:generate.",
    'import type { operations } from "./api.js";',
    "",
    "/** The HTTP method and the OpenAPI path template (with {name} segments) of one operation. */",
    'export interface OperationRoute {\n  readonly method: "GET" | "POST" | "PUT" | "DELETE" | "PATCH";\n  readonly path: string;\n}',
    "",
    "/** Every operation id the contract defines. */",
    "export type OperationId = keyof operations;",
    "",
    "/** The route of each operation. The type forces one entry per operation of the generated types. */",
    "export const OPERATIONS: { readonly [K in OperationId]: OperationRoute } = {",
    ...body,
    "};",
    "",
  ].join("\n");
}

/** Builds both generated files from a parsed OpenAPI document. Pure: nothing is written. */
export async function generateSdkFiles(spec: unknown): Promise<GeneratedFiles> {
  const rows = operationRows(spec as { paths?: Record<string, Record<string, unknown>> });
  // openapi-typescript may normalise its input in place, so it gets a copy.
  const ast = await openapiTS(structuredClone(spec) as Parameters<typeof openapiTS>[0], { silent: true });
  const header =
    "// Generated by scripts/generate-sdk.ts from docs/openapi.json (docs/decisions/0036). Do not edit by hand: run npm run sdk:generate.\n";
  return {
    "api.d.ts": header + astToString(ast),
    "operations.ts": operationsSource(rows),
  };
}

/** Writes generated files into a directory, creating it when needed. */
export async function writeSdkFiles(dir: string, files: GeneratedFiles): Promise<void> {
  await fs.mkdir(dir, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    await fs.writeFile(path.join(dir, name), text, "utf8");
  }
}

async function main(): Promise<void> {
  const spec = JSON.parse(await fs.readFile(SPEC_PATH, "utf8"));
  await writeSdkFiles(GENERATED_DIR, await generateSdkFiles(spec));
  console.log(`wrote ${path.relative(ROOT, path.join(GENERATED_DIR, "api.d.ts"))} and operations.ts`);
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
